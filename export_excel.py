"""
export_excel.py — Story 5 (starter). Kameryn owns the final layout.

Writes the plan as one block per term with a credit subtotal, plus a
grand total. Totals are Excel formulas, not Python numbers, so if an advisor
edits a course's credits in the sheet the totals update.
"""

import pandas as pd
from pathlib import Path
from typing import Dict, List

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side

FONT = "Arial"
HEADER_FILL = PatternFill("solid", start_color="1F3864")
TERM_FILL = PatternFill("solid", start_color="D9E1F2")
THIN = Side(style="thin", color="A6A6A6")


def write_plan(rows: List[Dict], path: Path, warnings: List[str] = ()) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Class Plan"

    ws["A1"] = "Recommended Class Plan"
    ws["A1"].font = Font(name=FONT, bold=True, size=14)
    ws["A2"] = "Required courses only. Generated by the Smart Class Planning Tool."
    ws["A2"].font = Font(name=FONT, italic=True, size=9, color="595959")

    headers = ["Term", "Course", "Title", "Credits"]
    for col, text in enumerate(headers, 1):
        cell = ws.cell(row=4, column=col, value=text)
        cell.font = Font(name=FONT, bold=True, color="FFFFFF")
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center")

    row = 5
    subtotal_cells = []
    df = pd.DataFrame(rows)
    terms = df["term"].drop_duplicates().tolist()
    for term in terms:
        first = row
        term_df = df[df["term"]==term]
        for _, r in term_df.iterrows():
            ws.cell(row=row, column=1, value=r["term"])
            ws.cell(row=row, column=2, value=r["course"])
            ws.cell(row=row, column=3, value=r["name"])
            ws.cell(row=row, column=4, value=r["credits"])
            for col in range(1, 5):
                c = ws.cell(row=row, column=col)
                c.font = Font(name=FONT)
                c.border = Border(bottom=THIN)
            row += 1
        last = row - 1

        ws.cell(row=row, column=3, value=f"{term} total").font = Font(name=FONT, bold=True)
        total = ws.cell(row=row, column=4, value=f"=SUM(D{first}:D{last})")
        total.font = Font(name=FONT, bold=True)
        for col in range(1, 5):
            ws.cell(row=row, column=col).fill = TERM_FILL
        subtotal_cells.append(f"D{row}")
        row += 2

    ws.cell(row=row, column=3, value="Total credits").font = Font(name=FONT, bold=True)
    grand = ws.cell(row=row, column=4, value="=" + "+".join(subtotal_cells) if subtotal_cells else 0)
    grand.font = Font(name=FONT, bold=True)

    for col, width in zip("ABCD", (16, 14, 36, 10)):
        ws.column_dimensions[col].width = width
    ws.freeze_panes = "A5"

    if warnings:
        wn = wb.create_sheet("Warnings")
        wn["A1"] = "Check these before relying on the plan"
        wn["A1"].font = Font(name=FONT, bold=True)
        for i, w in enumerate(warnings, 3):
            wn.cell(row=i, column=1, value=w).font = Font(name=FONT)
        wn.column_dimensions["A"].width = 90
    wb.save(path)

